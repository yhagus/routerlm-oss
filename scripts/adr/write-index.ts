import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type Adr, adrDir, frontmatterExample, knownAreas, readAdrs } from './adrs';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const INDEX = join(adrDir(ROOT), 'README.md');

function link(adr: Adr): string {
  return `[${adr.number} ${adr.title}](${adr.file})`;
}

function renderIndex(adrs: Adr[]): string {
  const live = adrs.filter((adr) => adr.status === 'accepted');
  const retired = adrs.filter((adr) => adr.status !== 'accepted');
  const areas = [...new Set(live.flatMap((adr) => adr.areas))].toSorted();
  const lines = [
    '# Architecture Decision Records',
    '',
    'Generated by `bun run adr:index` from the frontmatter of each ADR. Edit the ADRs, not this file.',
    '',
    'Each accepted ADR is listed under every area it governs. `backend` holds the rules for every module in `src/`.',
    '',
  ];
  for (const area of areas) {
    lines.push(`## ${area}`, '');
    for (const adr of live.filter((candidate) => candidate.areas.includes(area))) {
      lines.push(`- ${link(adr)}`);
    }
    lines.push('');
  }
  if (retired.length > 0) {
    lines.push('## Superseded and deprecated', '');
    for (const adr of retired) {
      const note =
        adr.supersededBy === undefined ? adr.status : `superseded by ${adr.supersededBy}`;
      lines.push(`- ${link(adr)}: ${note}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const { adrs, problems } = readAdrs(ROOT);
if (problems.length > 0) {
  for (const problem of problems) console.error(`docs/adr/${problem.file} ${problem.message}.`);
  console.error('\n' + frontmatterExample(knownAreas(ROOT)));
  process.exit(1);
}

const index = renderIndex(adrs);
if (process.argv.includes('--check')) {
  const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
  if (current !== index) {
    console.error('docs/adr/README.md is out of date: run `bun run adr:index`.');
    process.exit(1);
  }
} else {
  writeFileSync(INDEX, index);
}
